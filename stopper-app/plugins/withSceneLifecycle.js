const { withDangerousMod, withInfoPlist } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const MARKER = 'MARK: - UIScene lifecycle';

/*
 * iOS/iPadOS 27 refuses to launch an app that was built against the iOS 26+ SDK
 * and has not adopted the UIScene life cycle — the crash log names
 * __UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption. That is what
 * rejected build 95 on iPad.
 *
 * Declaring UIApplicationSceneManifest alone is NOT the fix, and build 96 is the
 * proof: it satisfies the adoption check, so UIKit then owns the scene, and the
 * AppDelegate's own `UIWindow(frame: UIScreen.main.bounds)` has no windowScene to
 * attach to. That build crashed on launch on iPhone as well as iPad.
 *
 * Expo SDK 56 and React Native 0.85 both still ship the pre-scene AppDelegate —
 * there is no UIWindowSceneDelegate anywhere in either package, and none in
 * react-native 0.87 either — so the adoption has to happen here.
 *
 * The scene, not the app delegate, creates the window and starts React Native in
 * it. URL and user-activity delivery moves with it: in a scene-based app those
 * callbacks no longer reach the app delegate, and this app depends on them —
 * Google OAuth comes back through stopper://.
 */

const SCENE_DELEGATE = `
// ${MARKER}
// Added by plugins/withSceneLifecycle.js — see that file for why this exists.
// ios/ is regenerated by prebuild, so do not hand-edit this block here.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene else { return }
    guard
      let appDelegate = UIApplication.shared.delegate as? AppDelegate,
      let factory = appDelegate.reactNativeFactory
    else { return }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window

    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: appDelegate.launchOptions
    )

    // A cold launch opened by a deep link delivers the URL here rather than
    // through scene(_:openURLContexts:).
    if let url = connectionOptions.urlContexts.first?.url {
      RCTLinkingManager.application(UIApplication.shared, open: url, options: [:])
    }
    if let userActivity = connectionOptions.userActivities.first {
      RCTLinkingManager.application(UIApplication.shared, continue: userActivity) { _ in }
    }
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    guard let url = URLContexts.first?.url else { return }
    RCTLinkingManager.application(UIApplication.shared, open: url, options: [:])
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    RCTLinkingManager.application(UIApplication.shared, continue: userActivity) { _ in }
  }
}
`;

/** The window block Expo's template puts in didFinishLaunchingWithOptions. */
const WINDOW_BLOCK =
  /#if os\(iOS\) \|\| os\(tvOS\)\s*\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\s*\n\s*factory\.startReactNative\([\s\S]*?\)\s*\n\s*#endif\n/;

function patchAppDelegate(contents) {
  if (contents.includes(MARKER)) return contents;

  if (!WINDOW_BLOCK.test(contents)) {
    throw new Error(
      '[withSceneLifecycle] Could not find the window/startReactNative block in ' +
        'AppDelegate.swift. The Expo template changed — update this plugin rather ' +
        'than shipping an app that will not launch on iOS 27.',
    );
  }

  // The scene starts React Native now, so the app delegate must not — but it
  // still has to keep the launch options around to hand over.
  let next = contents.replace(
    WINDOW_BLOCK,
    '    // React Native is started by SceneDelegate once the window scene exists.\n' +
      '    self.launchOptions = launchOptions\n',
  );

  next = next.replace(
    /(class AppDelegate: ExpoAppDelegate \{\n\s*var window: UIWindow\?\n)/,
    '$1  var launchOptions: [UIApplication.LaunchOptionsKey: Any]?\n',
  );

  if (!next.includes('var launchOptions:')) {
    throw new Error(
      '[withSceneLifecycle] Could not add launchOptions storage to AppDelegate.',
    );
  }

  return next.trimEnd() + '\n' + SCENE_DELEGATE;
}

module.exports = function withSceneLifecycle(config) {
  // The delegate class is appended to AppDelegate.swift rather than added as a
  // new file, so the Xcode target does not have to be touched.
  config = withDangerousMod(config, [
    'ios',
    async (cfg) => {
      const appDelegate = path.join(
        cfg.modRequest.platformProjectRoot,
        cfg.modRequest.projectName,
        'AppDelegate.swift',
      );
      const contents = fs.readFileSync(appDelegate, 'utf8');
      fs.writeFileSync(appDelegate, patchAppDelegate(contents));
      return cfg;
    },
  ]);

  return withInfoPlist(config, (cfg) => {
    cfg.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            // No UISceneStoryboardFile: the launch screen still comes from
            // UILaunchStoryboardName, and naming it here would make UIKit set a
            // storyboard root view controller that fights React Native's.
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
          },
        ],
      },
    };
    return cfg;
  });
};

module.exports.patchAppDelegate = patchAppDelegate;
