const { withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const MARKER = 'IPHONEOS_DEPLOYMENT_TARGET';

const BLOCK = `
    # Several pods (RNSVG filters, RevenueCat, PurchasesHybridCommon,
    # react-native-view-shot) still declare IPHONEOS_DEPLOYMENT_TARGET 12.4 in
    # their podspecs. CocoaPods does not raise those to the app's platform, and
    # current Xcode rejects anything below its supported range outright. Pin
    # every pod target to the app's minimum.
    min_ios = podfile_properties['ios.deploymentTarget'] || '16.4'
    installer.pods_project.targets.each do |target|
      target.build_configurations.each do |config|
        current = config.build_settings['IPHONEOS_DEPLOYMENT_TARGET']
        if current.nil? || Gem::Version.new(current) < Gem::Version.new(min_ios)
          config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = min_ios
        end
      end
    end
`;

/**
 * ios/ is gitignored and regenerated by `expo prebuild`, which would drop a
 * hand-edited Podfile. This re-applies the deployment-target floor every time
 * the native project is generated.
 */
module.exports = function withPodDeploymentTarget(config) {
  return withDangerousMod(config, [
    'ios',
    async (cfg) => {
      const podfile = path.join(cfg.modRequest.platformProjectRoot, 'Podfile');
      let contents = fs.readFileSync(podfile, 'utf8');

      if (contents.includes(MARKER)) return cfg;

      contents = contents.replace(
        /(\n\s*post_install do \|installer\|\n)/,
        `$1${BLOCK}`,
      );

      fs.writeFileSync(podfile, contents);
      return cfg;
    },
  ]);
};
